-- ---------------------------------------------------------------------
-- RESET (destructive — commented out on purpose)
--
-- Neither this script nor the server alters an existing table. After
-- changing a column in a *Table.kt file, drop the tables and run this
-- script again. This deletes ALL data, not just the seed rows.
-- ---------------------------------------------------------------------
-- DROP TABLE IF EXISTS ratings;
-- DROP TABLE IF EXISTS events;
-- DROP TABLE IF EXISTS users;

-- ---------------------------------------------------------------------
-- Summary
-- ---------------------------------------------------------------------
SELECT table_name AS created_table
FROM information_schema.tables
WHERE table_schema = 'orbit_database'
ORDER BY table_name;
