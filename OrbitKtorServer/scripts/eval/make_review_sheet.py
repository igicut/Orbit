"""
Pravi LABELS_REVIEW.md iz dva JSON fajla sa oznakama, sa naslovima dogadjaja pored id-jeva.
JSON fajlovi su izvor istine; ovaj list je samo za lakse citanje i treba ga ponovo napraviti
posle svake izmene oznaka. Naslove cita preko API-ja, pa server mora da radi nad orbit_eval.
"""
import json

from eval_common import HERE, call, cell, full_id, login

LAT, LNG = 44.8125, 20.4612


def main():
    token = login("milica")
    status, events = call("GET", f"/events?lat={LAT}&lng={LNG}", token=token)
    assert status == 200, (status, events)
    titles = {event["id"]: event["title"] for event in events}
    semantic = json.loads((HERE / "semantic_labels.json").read_text(encoding="utf-8"))
    parse = json.loads((HERE / "parse_labels.json").read_text(encoding="utf-8"))

    def names(ids):
        return "<br>".join(f"`{i}` {cell(titles.get(full_id(i), '?'))}" for i in ids) or "—"

    lines = ["# Evaluation labels — review sheet", "",
             f"**Semantic labels:** {semantic['status']}", "",
             f"**Parse labels:** {parse['status']}", "",
             "Generated by `make_review_sheet.py` from the two JSON files, which are the source of truth.", "",
             "## Point 9 — semantic search relevance", "",
             f"Corpus: {semantic['corpus']['description']}.", "",
             f"Rule: {semantic['relevance_rule']}", "",
             "Frozen thresholds: " + ", ".join(f"`{k} = {v}`" for k, v in semantic["thresholds_frozen"].items()
                                              if k != "note") + ".", ""]
    for part, heading in (("tuning", "Tuning set — the queries the thresholds were chosen on"),
                          ("test", "Test set — new queries, never run before the labels were frozen")):
        lines += [f"### {heading}", "", "| # | Query | Relevant | Borderline | Note |", "|---|---|---|---|---|"]
        for number, q in enumerate(semantic[part], start=1):
            note = q["note"] + (" **Excluded from the averages.**" if q.get("exclude_from_averages") else "")
            lines.append(f"| {number} | {cell(q['query'])} | {names(q['relevant'])} | {names(q['borderline'])} | "
                         f"{cell(note)} |")
        lines.append("")

    def show(value):
        if value is None:
            return "—"
        if isinstance(value, dict):
            return "not " + ", ".join(value["not"])
        return " or ".join("—" if v is None else v for v in value)

    lines += ["## Point 10 — filters extracted from a sentence", "",
              "Each cell lists the acceptable answers; `—` means the field must be left out, `not X` means "
              "anything except X. Fields not shown must be left out.", "",
              "| # | Kind | Sentence | Category | Price | Time | Distance | Sort | Note |",
              "|---|---|---|---|---|---|---|---|---|"]
    for s in parse["sentences"]:
        cells = [show(s["expected"].get(f)) for f in ("category", "price", "dateWindow", "radius", "sort")]
        lines.append(f"| {s['id']} | {s['kind']} | {cell(s['text'])} | " + " | ".join(cells) +
                     f" | {cell(s.get('note', ''))} |")

    (HERE / "LABELS_REVIEW.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("written LABELS_REVIEW.md")


if __name__ == "__main__":
    main()
